MODULE_TEMPLATE = '''r"""{title}

Layer: L2

Generated by Settings -> File types -> Add file type. The contract below is
already correct; the parsing is the part to write.

**The rules that matter, and why:**

* The library is imported **inside** `extract()`. At module level, a machine
  without it fails to start the whole application instead of one file type
  reporting a fix.
* Failure is a value, not an exception. A corrupt file in a 100GB run is
  Tuesday: raise `AppErrorException` (via `raise_error`) for a file that cannot
  be read at all, and attach `builder.warn(...)` for a file that is readable but
  degraded - it still gets indexed.
* Never yield an empty document. `extract()` treats empty as
  `ERR_NO_TEXT_LAYER` and the file leaves the index entirely. If it is still
  worth finding by name, emit the name with a warning saying why the contents
  are missing.
"""

from __future__ import annotations

from pathlib import Path
from typing import Iterable

from app.core.errors import make_error, raise_error
from app.core.format_health import Requirement
from app.extract.base import Document, DocumentBuilder, register


class {class_name}:
    """{summary}"""

    name = "{name}"
    extensions = frozenset({{{extensions}}})
    reads_externally = {reads_externally}
{requires_block}
    def supports(self, path: Path) -> bool:
        return path.suffix.lower() in self.extensions

    def extract(self, path: Path) -> Iterable[Document]:
{import_block}
        builder = DocumentBuilder(path)

        # ------------------------------------------------------------------
        # TODO: read `path` and add what is worth searching.
        #
        #   builder.add(text, page=1, label="Section name", prefix_label=True)
        #
        # `page` reaches the `chunks.page` column, so a result can say where in
        # the file it came from. `label` names it on screen; `prefix_label=True`
        # also writes the label into the indexed text, which is how a sheet or
        # slide name becomes searchable - there is no column for it.
        #
        # Offsets are maintained for you: `DocumentBuilder` records each
        # segment's position as it appends, so highlighting keeps working.
        # ------------------------------------------------------------------
        raise NotImplementedError(
            "{name}: the reader is scaffolded but not written yet"
        )

        document = builder.build()
        if document.is_empty:
            yield self._name_only(path, "No text could be read from this file.")
            return
        yield document

    def _name_only(self, path: Path, reason: str) -> Document:
        """The file as its name, when the contents cannot be read.

        Never an empty document: empty means the file disappears from the index
        altogether, and a file somebody searches for by name is exactly the one
        that must not.
        """
        builder = DocumentBuilder(path)
        builder.add(path.stem.replace("_", " ").replace("-", " "), label="File name")
        builder.warn(make_error(
            "ERR_NO_TEXT_LAYER", "extract.{name}",
            path=str(path), details=reason,
            suggestion="The file is indexed by its name.",
        ))
        return builder.build()


register({class_name}())
'''

_REQUIRES_BLOCK = '''    #: Declared so Settings and `doctor.py` can report this format's real state
    #: and offer the exact install command, instead of leaving somebody to infer
    #: a missing package from an empty result set.
    requires = (
        Requirement("{module}", "{package}",
                    provides="{provides}",
                    hard={hard}),
    )
'''

_IMPORT_BLOCK = '''        try:
            import {module}  # noqa: PLC0415 - lazy by design, see the docstring
        except ImportError:
            raise_error(
                "ERR_UNSUPPORTED_TYPE", "extract.{name}",
                path=str(path), ext=path.suffix.lower(),
                suggestion=r"venv\\Scripts\\pip install {package}",
            )
'''

_NO_IMPORT_BLOCK = '''        # No third-party library: this reads the file with the standard library.
'''


