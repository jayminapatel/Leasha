r"""Generate a new extractor: the module, the import, the pin.

Layer: L0

Adding a file type that needs its own parser is six steps, five of which are
identical every time and one of which is the actual work. The five are where it
goes wrong - forget the line in `app/extract/_readers.py` and `register()` never
runs, so the extension reports as unsupported and nothing anywhere says why.
(That list of imports lived in `app/extract/__init__.py` until work order 0r
item 2b moved it one file sideways, so that importing the package no longer
imports every parser before the window is on screen. The line is the same line,
in the same alphabetical place; only the file it goes in changed.)

**This generates the five and leaves the one.** The module arrives with the
contract already correct - lazy import, declared `requires`, errors as values,
never an empty document - and a single `TODO` where the parsing goes.

**It writes into the application's own source tree**, which is a serious thing
for a running program to do, so:

* Nothing is written until `apply()` is called, and `plan()` returns exactly
  what would change so it can be shown first.
* An existing file is never overwritten. A name already taken is refused, with
  the path that holds it.
* Every edit is append-or-insert at a known anchor, never a rewrite - a
  generator that reformats `_readers.py` would eventually eat something.
* A frozen build has no source tree to write to and refuses outright rather
  than writing into a temporary directory nobody will ever look at.

The generated module is deliberately verbose. Somebody reading it in six months
is more likely to be maintaining it than admiring it.
"""

from __future__ import annotations

import keyword
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Optional

from app.core.errors import AppErrorException, make_error

__all__ = [
    "ExtractorSpec",
    "ScaffoldPlan",
    "FileChange",
    "plan",
    "apply",
    "project_root",
    "MODULE_TEMPLATE",
]

#: A reader name has to be a valid Python identifier *and* readable in config,
#: where it appears as `extractor = "name"`.
_NAME = re.compile(r"^[a-z][a-z0-9_]{1,30}$")

#: `.dxf`, `.tar.gz` is not supported - the registry keys on `Path.suffix`,
#: which is the last component only.
_EXTENSION = re.compile(r"^\.[a-z0-9][a-z0-9+-]{0,15}$")


def project_root() -> Path:
    """The repository root: the folder holding `app/` and `requirements.txt`."""
    return Path(__file__).resolve().parents[2]


def _fail(reason: str, *, suggestion: str = "") -> None:
    raise AppErrorException(make_error(
        "ERR_CONFIG_INVALID", "core.scaffold",
        key="new file type", reason=reason, suggestion=suggestion,
    ))


@dataclass(frozen=True, slots=True)
class ExtractorSpec:
    """What the person answered. Everything else is derived."""

    name: str                       # reader name, e.g. "cad"
    extensions: tuple[str, ...]     # (".dxf",)
    module: str = ""                # import name, e.g. "ezdxf" - blank if none
    package: str = ""               # pip name, e.g. "ezdxf"
    provides: str = ""              # what is lost without it
    hard: bool = True               # no library -> nothing readable at all?
    reads_externally: bool = False  # read through another application
    max_bytes: int = 0              # 0 -> use the default cap
    version: str = ""               # pin, e.g. "1.4.2" - blank for unpinned

    @property
    def module_file(self) -> str:
        return f"{self.name}.py"

    @property
    def class_name(self) -> str:
        return f"{self.name.title().replace('_', '')}Extractor"


@dataclass(frozen=True, slots=True)
class FileChange:
    """One file to create or amend, with the text that would end up in it."""

    path: Path
    content: str
    action: str                     # "create" | "amend"
    summary: str = ""


@dataclass(frozen=True, slots=True)
class ScaffoldPlan:
    """Everything that would change, and nothing done yet."""

    spec: ExtractorSpec
    changes: list[FileChange] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)

    @property
    def paths(self) -> list[Path]:
        return [change.path for change in self.changes]


