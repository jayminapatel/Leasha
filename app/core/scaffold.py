def _validate(spec: ExtractorSpec, root: Path) -> None:
    if not _NAME.match(spec.name):
        _fail(
            f"{spec.name!r} is not a usable reader name",
            suggestion="Lower case, starting with a letter, letters/digits/"
                       "underscores only - for example 'cad' or 'auto_cad'.",
        )
    if keyword.iskeyword(spec.name):
        _fail(f"{spec.name!r} is a Python keyword and cannot be a module name")

    if not spec.extensions:
        _fail("no file extension was given",
              suggestion="At least one, for example '.dxf'.")

    for extension in spec.extensions:
        if not _EXTENSION.match(extension):
            _fail(
                f"{extension!r} is not a file extension",
                suggestion="Lower case, one leading dot, no spaces - '.dxf'.",
            )

    if spec.package and not spec.module:
        _fail("a package was named but not the module to import",
              suggestion="For python-docx the import is 'docx'; for pymupdf it "
                         "is 'fitz'. They are frequently different.")

    target = root / "app" / "extract" / spec.module_file
    if target.exists():
        _fail(f"{target.name} already exists",
              suggestion=f"Choose another name, or edit {target} directly.")

    taken = _claimed_extensions(root)
    for extension in spec.extensions:
        if extension in taken:
            _fail(
                f"{extension} is already read by the {taken[extension]!r} reader",
                suggestion="Two readers claiming one extension is refused at "
                           "startup. Edit that reader instead, or choose a "
                           "different extension.",
            )


def _claimed_extensions(root: Path) -> dict[str, str]:
    """Extension -> reader name, from the live registry when it can be read.

    Best effort: a partially broken tree must not stop the generator, and the
    duplicate claim would then be caught at startup instead - later, but never
    silently.
    """
    try:
        import app.extract  # noqa: F401 - registration side effects
        from app.extract.base import REGISTRY

        return {
            extension: str(getattr(extractor, "name", "?"))
            for extension, extractor in REGISTRY.items()
        }
    except Exception:                              # noqa: BLE001
        return {}


def _render_module(spec: ExtractorSpec) -> str:
    extensions = ", ".join(f'"{extension}"' for extension in spec.extensions)
    listed = ", ".join(spec.extensions)

    if spec.module:
        requires = _REQUIRES_BLOCK.format(
            module=spec.module,
            package=spec.package or spec.module,
            provides=spec.provides or "the contents of these files",
            hard="True" if spec.hard else "False",
        )
        imports = _IMPORT_BLOCK.format(
            module=spec.module,
            name=spec.name,
            package=spec.package or spec.module,
        )
    else:
        requires = ""
        imports = _NO_IMPORT_BLOCK

    return MODULE_TEMPLATE.format(
        title=f"{listed} files, read for their text.",
        class_name=spec.class_name,
        summary=f"{listed} files.",
        name=spec.name,
        extensions=extensions,
        reads_externally=spec.reads_externally,
        requires_block=requires,
        import_block=imports,
    )


def _amend_init(root: Path, spec: ExtractorSpec) -> Optional[FileChange]:
    """Insert the import that makes `register()` actually run.

    **The step that is forgotten**, and its failure mode is the worst kind:
    the module is perfect, the extension reports unsupported, and nothing
    connects the two. Inserted in alphabetical order among the existing
    extractor imports so the file stays as it was written.

    The file is `app/extract/_readers.py`, not the package's `__init__.py`:
    see this module's own docstring, and `_readers.py`'s.
    """
    path = root / "app" / "extract" / "_readers.py"
    text = path.read_text(encoding="utf-8")
    line = f"from app.extract import {spec.name} as {spec.name}  # noqa: F401,E402"

    if line in text:
        return None

    lines = text.splitlines()
    marker = "from app.extract import "
    positions = [i for i, entry in enumerate(lines) if entry.startswith(marker)]
    if not positions:
        _fail(
            "app/extract/_readers.py has no extractor imports to insert beside",
            suggestion=f"Add this line by hand:  {line}",
        )

    insert_at = positions[-1] + 1
    for position in positions:
        existing = lines[position][len(marker):].split(" ")[0]
        if existing > spec.name:
            insert_at = position
            break

    lines.insert(insert_at, line)
    return FileChange(
        path=path,
        content="\n".join(lines) + "\n",
        action="amend",
        summary=f"import {spec.name} so register() runs",
    )


def _amend_requirements(root: Path, spec: ExtractorSpec) -> Optional[FileChange]:
    """Pin the package, so the next machine installs it too."""
    if not spec.package:
        return None

    path = root / "requirements.txt"
    text = path.read_text(encoding="utf-8")
    if re.search(rf"^{re.escape(spec.package)}\b", text, re.MULTILINE):
        return None

    pin = f"{spec.package}=={spec.version}" if spec.version else spec.package
    listed = ", ".join(spec.extensions)
    addition = (
        f"\n{pin}"
        f"{' ' * max(1, 22 - len(pin))}# {listed} - added by Settings\n"
    )
    return FileChange(
        path=path,
        content=text.rstrip("\n") + "\n" + addition,
        action="amend",
        summary=f"pin {pin}",
    )


def plan(spec: ExtractorSpec, root: Optional[Path] = None) -> ScaffoldPlan:
    """What adding this reader would change. Writes nothing.

    Raises `AppErrorException` with a usable suggestion for anything that would
    not work - a name already taken, an extension another reader claims, an
    extension that is not one.
    """
    root = Path(root) if root else project_root()

    if getattr(sys, "frozen", False):
        _fail(
            "this is a packaged build, which has no source tree to add a reader to",
            suggestion="Add the file type in a development checkout, then "
                       "rebuild. Existing formats can still be configured here.",
        )

    _validate(spec, root)

    changes = [FileChange(
        path=root / "app" / "extract" / spec.module_file,
        content=_render_module(spec),
        action="create",
        summary=f"the {spec.name} reader for {', '.join(spec.extensions)}",
    )]

    for change in (_amend_init(root, spec), _amend_requirements(root, spec)):
        if change is not None:
            changes.append(change)

    notes = [
        f"Open app/extract/{spec.module_file} and replace the TODO with the "
        "parsing - everything around it is already correct.",
        "Restart the application: extractors register on import, so a new one "
        "is not picked up by a running process.",
    ]
    if spec.package:
        notes.insert(0, f"Install the library: venv\\Scripts\\pip install {spec.package}")
    if spec.max_bytes:
        notes.append(
            f"Set the size cap to {spec.max_bytes // (1 << 20)}MB in Settings "
            "once the reader is working."
        )

    return ScaffoldPlan(spec=spec, changes=changes, notes=notes)


def apply(scaffold: ScaffoldPlan) -> list[Path]:
    """Write the plan. Returns the paths written, in order.

    Creates are checked again immediately before writing: a plan can be shown
    on screen for as long as somebody takes to read it, and a file that
    appeared in the meantime must not be overwritten by a stale decision.
    """
    written: list[Path] = []
    for change in scaffold.changes:
        if change.action == "create" and change.path.exists():
            _fail(f"{change.path.name} appeared while the plan was on screen",
                  suggestion="Nothing was overwritten. Choose another name.")
        change.path.parent.mkdir(parents=True, exist_ok=True)
        temporary = change.path.with_suffix(change.path.suffix + ".tmp")
        temporary.write_text(change.content, encoding="utf-8")
        temporary.replace(change.path)
        written.append(change.path)
    return written
