def receipt_to_result(receipt: Any, rank: int) -> Any:
    """A `Receipt` as the `SearchResult` the results list already draws.

    The Sources pane is the same list search uses (3a), so the same row
    upgrades flow in without re-implementing any of them. A receipt with no
    file id (a mail message the index could not name) gets a stable negative
    one so two of them never fold into a single card.
    """
    from app.search.engine import SearchResult

    path = str(getattr(receipt, "path", "") or "")
    file_id = getattr(receipt, "file_id", None)
    if file_id is None:
        file_id = -(zlib.crc32(path.encode("utf-8", "replace")) % 1_000_000_000) - 1
    chunk_id = getattr(receipt, "chunk_id", None)
    if chunk_id is None:
        chunk_id = -1_000_000 - int(rank)
    return SearchResult(
        chunk_id=int(chunk_id), file_id=int(file_id), path=path,
        text=str(getattr(receipt, "quote", "") or ""), score=1.0,
        rank=int(rank), label=str(getattr(receipt, "locator", "") or ""))


def passage_html(number: int, receipt: Any) -> str:
    """The exact passage a source stands on, for the strip under the list."""
    quote = html.escape(str(getattr(receipt, "quote", "") or ""))
    where = html.escape(str(getattr(receipt, "locator", "") or ""))
    name = html.escape(str(getattr(receipt, "name", "") or ""))
    head = f"<b>{number}</b> &nbsp;{name}" + (f" &middot; {where}" if where else "")
    return f"{head}<br><i>&ldquo;{quote}&rdquo;</i>"


# ---------------------------------------------------------------------------
# The shelf
# ---------------------------------------------------------------------------

@dataclass
class ShelfItem:
    path: str
    name: str
    file_id: Optional[int] = None
    pinned: bool = False


@dataclass
class Shelf:
    """The documents the assistant may look at, and only those (3c)."""

    items: list[ShelfItem] = field(default_factory=list)
    #: Paths the person took off. A later mention does not put them back;
    #: only an explicit add (a drag) does - out of scope means out of scope.
    removed: set[str] = field(default_factory=set)

    def _find(self, path: str) -> Optional[ShelfItem]:
        return next((i for i in self.items if i.path == path), None)

    def add(self, path: str, name: str = "", file_id: Optional[int] = None, *,
            explicit: bool = False) -> bool:
        """Put a document on the shelf. False if it is there or was removed."""
        if not path:
            return False
        if path in self.removed and not explicit:
            return False
        self.removed.discard(path)
        if self._find(path) is not None:
            return False
        tail = re.split(r"[\\/]", path)[-1]
        self.items.append(ShelfItem(path, name or tail, file_id, pinned=explicit))
        self._trim()
        return True

    def add_receipt(self, receipt: Any) -> bool:
        return self.add(str(getattr(receipt, "path", "") or ""),
                        str(getattr(receipt, "name", "") or ""),
                        getattr(receipt, "file_id", None))

    def remove(self, path: str) -> None:
        self.items = [i for i in self.items if i.path != path]
        self.removed.add(path)

    def toggle_pin(self, path: str) -> bool:
        item = self._find(path)
        if item is None:
            return False
        item.pinned = not item.pinned
        return item.pinned

    def _trim(self) -> None:
        loose = [i for i in self.items if not i.pinned]
        while len(loose) > MAX_UNPINNED:
            oldest = loose.pop(0)
            self.items.remove(oldest)

    def paths(self) -> list[str]:
        """Pinned first: what a follow-up searches before the rest."""
        ordered = sorted(self.items, key=lambda i: not i.pinned)
        return [i.path for i in ordered]

    def to_dict(self) -> dict:
        return {"items": [vars(i).copy() for i in self.items],
                "removed": sorted(self.removed)}

    @classmethod
    def from_dict(cls, data: Optional[dict]) -> "Shelf":
        data = data or {}
        items = [ShelfItem(str(d.get("path", "")), str(d.get("name", "")),
                           d.get("file_id"), bool(d.get("pinned", False)))
                 for d in data.get("items", ()) if d.get("path")]
        return cls(items, {str(p) for p in data.get("removed", ())})


