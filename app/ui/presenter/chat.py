PLACEHOLDER = ("Ask about your files and mail. Enter sends; "
               "Shift+Enter starts a new line.")
EMPTY_HEADING = "Ask about anything you have kept."
EMPTY_HINT = ("For example: What did we agree with the landlord about the "
              "deposit?  Show me the photos from the beach in 2015.  "
              "How many PDFs did Dave send in 2019?")
STOPPED_LINE = "Stopped. That is as far as it got."
FAILED_LINE = ("That did not work this time. Searching is not affected. "
               "Try asking again in a moment.")
NOT_BUILT_LINE = ("Chat is not part of this copy of Leasha yet. "
                  "Searching works exactly the same.")
SHELF_EMPTY = "Documents this chat uses will appear here."

#: A sentence to show when the helper program is missing, if the engine gave
#: no reason of its own. Says what to install and that search is unaffected.
_DEFAULT_UNAVAILABLE = (
    "Chat needs a free helper program called Ollama, running on this "
    "computer. Install it from ollama.com, start it, then press Check again. "
    "Searching works the same with or without it.")

#: Words that make a banner into a stigma. Nothing the tab says may match.
#: (3a: "No 'AI-generated, verify!' banners anywhere".) The test that reads
#: every fixed string in the tab imports this, so the list lives beside the
#: strings it polices.
WARNING_WORDS = (
    r"ai[- ]generated", r"generated by ai", r"\bverify\b", r"double[- ]check",
    r"may (?:be )?(?:inaccurate|incorrect|wrong)", r"can make mistakes",
    r"not (?:always )?(?:accurate|reliable)", r"hallucinat", r"disclaimer",
    r"use with caution", r"be careful", r"as an ai\b", r"\bbeta\b",
    r"experimental", r"\bwarning\b", r"check important",
)

#: Shelf items kept without being pinned. Pinned ones never drop off.
MAX_UNPINNED = 12

#: `[3]` - the marker the engine leaves in the prose where a source belongs.
MARKER = re.compile(r"\[(\d{1,3})\]")
_OPEN_MARKER_TAIL = re.compile(r"\[\d{0,3}$")


def unavailable_text(reason: str = "") -> str:
    """What the page says when there is no helper to answer. Never a trace."""
    reason = (reason or "").strip()
    return reason if reason else _DEFAULT_UNAVAILABLE


# ---------------------------------------------------------------------------
# Numbering - first mention, never changes
# ---------------------------------------------------------------------------

class Numbering:
    """Engine marker number -> the number the reader sees.

    Assigned in the order the prose first points at each source, so number 1
    is always the first thing the answer leaned on. Once assigned, fixed.
    """

    def __init__(self) -> None:
        self._map: dict[int, int] = {}

    def display(self, engine_number: int) -> int:
        if engine_number not in self._map:
            self._map[engine_number] = len(self._map) + 1
        return self._map[engine_number]

    def known(self, engine_number: int) -> Optional[int]:
        return self._map.get(engine_number)

    def feed(self, text: str) -> list[int]:
        """Number every marker in `text`; return the engine numbers that are new."""
        fresh: list[int] = []
        for match in MARKER.finditer(text or ""):
            number = int(match.group(1))
            if number not in self._map:
                fresh.append(number)
            self.display(number)
        return fresh

    def in_order(self) -> list[int]:
        """Engine numbers, in the order the reader met them."""
        return sorted(self._map, key=self._map.get)

    def __len__(self) -> int:
        return len(self._map)


def render_answer_html(text: str, numbering: Numbering,
                       linkable: Iterable[int] = ()) -> str:
    """The answer as small rich text: raised, clickable source numbers.

    A marker still arriving (`[1` at the very end of the text so far) is held
    back rather than drawn, so the reader never sees a number appear as
    brackets and then turn into a link. Text is escaped - an answer quoting a
    document containing `<b>` must not become markup.
    """
    text = _OPEN_MARKER_TAIL.sub("", text or "")
    can_link = set(linkable)
    out: list[str] = []
    last = 0
    for match in MARKER.finditer(text):
        out.append(html.escape(text[last:match.start()]))
        engine_number = int(match.group(1))
        shown = numbering.display(engine_number)
        if engine_number in can_link:
            out.append(f'<sup><a href="receipt:{shown}">{shown}</a></sup>')
        else:
            out.append(f"<sup>{shown}</sup>")
        last = match.end()
    out.append(html.escape(text[last:]))
    return "".join(out).replace("\n", "<br>")


