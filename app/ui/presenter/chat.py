def closing_line(turn: Any, *, stopped: bool = False) -> str:
    """The quiet last line of an answer, when it needs one (4e-4).

    A FIND answer's grid says "That's all - N results." itself (the results
    list ends that way). What is left is the edge nothing else states: a
    search that found nothing, and an answer somebody cut short.
    """
    if stopped:
        return STOPPED_LINE
    if turn is None:
        return ""
    if getattr(turn, "kind", "") == "find" and not getattr(turn, "result_set", None):
        return "Nothing in what Leasha has indexed matches that."
    return ""


def title_from_question(question: str, limit: int = 48) -> str:
    """A session's first name: the opening of the first question."""
    words = " ".join((question or "").split())
    if not words:
        return "New chat"
    if len(words) <= limit:
        return words
    cut = words[:limit].rsplit(" ", 1)[0] or words[:limit]
    return cut.rstrip(",.;:") + "..."
