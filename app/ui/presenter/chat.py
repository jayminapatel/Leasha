"""The Chat tab's decisions: what to say, how to number, what is on the shelf.

Layer: L5 (no Qt - the widgets in `app/ui/widgets/chat_*.py` only draw this)

Work order 202626270611 section 3. Everything here can be tested without a
display, which matters most for the two rules that are easy to break quietly:

* **Numbering is first-mention and never changes** (4e-2). `Numbering` hands
  out 1, 2, 3 in the order the answer first points at a source, and a number
  once given is never given again to something else - so the small raised
  number a reader is about to click is still the same source a moment later.
* **The shelf is exactly what the assistant may look at** (3c). `Shelf` is the
  one list; the tab draws it and the engine is told to search it first.

**No badges** (3a). Not one fixed string here warns that an answer "may be
wrong" - the honesty is in the receipts, not in a disclaimer. `test_chat_tab`
scans every string in the tab against `WARNING_WORDS`.
"""

